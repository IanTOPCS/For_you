// timer 3 interrupt
void TIM3_IRQHandler(void) {
	if(TIM_GetITStatus(TIM3,TIM_IT_Update)==SET) {
		if (stopContinue == 0) {
			OLED_Bmp001();
			OLED_Bmp002();
			// shift Bmp001(student-id) to right
			shiftBlock(Bmp001, stdIdFg);
			// shift Bmp002(name) to left
			shiftBlock(Bmp002, stdNameFg);
		}
	}
	TIM_ClearITPendingBit(TIM3,TIM_IT_Update);
}

// for chinese name (to left)
void OLED_Bmp001() {
	u16 i,j;
	for(i=0; i<height; i++) {
		OLED_Set_Pos(0,i);
		for(j=0;j<len;j++) {
			OLED_WR_Byte(Bmp001[i*len+j],OLED_DATA);
		}
	}
}

// for student-id (to right)
void OLED_Bmp002() {
	u16 i,j;
	for(i=0; i<height; i++) {
		OLED_Set_Pos(0,i+height);
		for(j=0;j<len;j++) {
			OLED_WR_Byte(Bmp002[i*len+j],OLED_DATA);
		}
	}
}

// mode 0: left, 1: right
void shiftBlock(unsigned char* sor, bool mode) {
    u16 i, col, offset, row;
    unsigned char tmp;
	// adjust left-right
	if (lrOrUd == 0) {
		for (i = 0; i < height; i++) {
			// get begin of row
			offset = i * len;
			// shift left
			if (mode == 0) {
				tmp = sor[offset];
				// cover from next one
				for (col = 0; col < (len-1); col++) {
					sor[offset + col] = sor[offset + col + 1];
				}
				// set the last one
				sor[offset + (len-1)] = tmp;
			} else if (mode == 1) {
				// shift right
				// get last one
				tmp = sor[offset + (len-1)];
				// cover from back one
				for (col = (len-1); col > 0; col--) {
					sor[offset + col] = sor[offset + col - 1];
				}
				// set the first one
				sor[offset] = tmp;
			}
		}
	} else if (lrOrUd == 1) {
		// adjust up-down
		for(i = 0; i < len; i++) {
			// shift up
			if (mode == 0) {
				tmp = sor[i];
				for(row=0; row<(height-1); row++) {
					sor[(len*row) + i] = sor[(len*(row+1)) + i];
				}
				sor[i + (len*(height-1))] = tmp;

			} else if (mode == 1) {
				// shift down
				tmp = sor[i + (len*(height-1))];
				for(row=(height-1); row>0; row--) {
					sor[(len*row) + i] = sor[(len*(row-1)) + i];
				}
				sor[i] = tmp;
			}
		}
	}
	return;
}

